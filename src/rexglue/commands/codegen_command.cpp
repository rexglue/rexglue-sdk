Result<std::string> DiscoverManifestInCwd() {
  std::error_code ec;
  fs::path cwd = fs::current_path(ec);
  if (ec) {
    return Err<std::string>(rex::ErrorCategory::IO,
                            std::format("Cannot read current directory: {}", ec.message()));
  }

  std::vector<fs::path> manifests;
  std::vector<fs::path> other_tomls;
  for (const auto& entry : fs::directory_iterator(cwd, ec)) {
    if (ec)
      break;
    if (!entry.is_regular_file())
      continue;
    if (entry.path().extension() != ".toml")
      continue;
    auto stem = entry.path().stem().string();
    if (stem.size() >= 9 && std::string_view{stem}.substr(stem.size() - 9) == "_manifest") {
      manifests.push_back(entry.path());
    } else {
      other_tomls.push_back(entry.path());
    }
  }

  if (manifests.size() == 1)
    return rex::Ok(manifests.front().string());
  if (manifests.size() > 1) {
    return Err<std::string>(
        rex::ErrorCategory::Config,
        std::format("Multiple *_manifest.toml files in {}; pass one explicitly", cwd.string()));
  }
  if (other_tomls.size() == 1)
    return rex::Ok(other_tomls.front().string());
  if (other_tomls.size() > 1) {
    return Err<std::string>(
        rex::ErrorCategory::Config,
        std::format("Multiple .toml files in {}; pass the manifest explicitly", cwd.string()));
  }
  return Err<std::string>(rex::ErrorCategory::Config,
                          std::format("No manifest .toml found in {}", cwd.string()));
}

Result<void> CodegenFromConfig(const std::string& config_path, const CLIContext& ctx,
                               const std::vector<std::string>& targets, bool ignore_stamp,
                               const rex::codegen::Limits& limits) {
  REXLOG_TRACE(rexglue, "Generating code with config: {}", config_path);

  fs::path manifest_path = config_path;
  if (!rex::codegen::ManifestConfig::IsManifest(manifest_path)) {
    return Err<void>(
        rex::ErrorCategory::Config,
        std::format("{} is not a manifest: no [project] section. Pre-manifest single-file "
                    "configs are no longer converted automatically; see docs for the layout.",
                    config_path));
  }

  auto loaded = LoadManifestSummary(manifest_path);
  if (!loaded)
    return Err<void>(loaded.error());
  auto summary = std::move(*loaded);

  const std::string current_version = REXGLUE_VERSION_FLOOR;
  EmitProjectHeader(manifest_path, summary);

  if (RefreshGeneratedGlue(manifest_path.parent_path(), summary.project_name, current_version,
                           summary.entrypoint_out_dir)) {
    REXLOG_INFO(rexglue, "Regenerated generated/rexglue.cmake for SDK v{}", current_version);
  }

  if (auto run_result = RecompileProject(manifest_path, ctx, targets, ignore_stamp, limits);
      !run_result) {
    return run_result;
  }

  if (!rex::codegen::ManifestConfig::WriteSDKVersionStamp(manifest_path, current_version)) {
    REXLOG_WARN(rexglue, "Failed to stamp manifest sdkVersion");
  }
  return rex::Ok();
}

void RegisterCodegen(CLI::App& parent, const CLIContext& ctx, DeferredAction& pending) {
  auto args = std::make_shared<CodegenArgs>();
  auto* sub = parent.add_subcommand("codegen", "Analyze and generate C++ code")->fallthrough();
  sub->add_option("config", args->config_path,
                  "Path to manifest TOML (auto-discovered in cwd if omitted)")
      ->type_name("PATH");
  sub->add_option("--target", args->targets,
                  "DLL target to build (repeatable; entrypoint always included)")
      ->type_name("NAME")
      ->take_all();
  sub->add_flag("--ignore-stamp", args->ignore_stamp,
                "Regenerate even when inputs match the recorded stamp");
  sub->add_option("--max_file_size_bytes", args->limits.max_file_size_bytes,
                  "Largest generated source file in bytes")
      ->check(CLI::Range(65536u, 67108864u));
  sub->add_option("--max_discovery_iterations", args->limits.max_discovery_iterations,
                  "Discovery passes")
      ->check(CLI::Range(1u, 100000u));
  sub->add_option("--max_vtable_iterations", args->limits.max_vtable_iterations,
                  "Vtable resolution passes")
      ->check(CLI::Range(1u, 100000u));
  sub->add_option("--max_resolve_iterations", args->limits.max_resolve_iterations,
                  "Merge resolution passes")
      ->check(CLI::Range(1u, 100000u));
  sub->add_option("--max_eh_states", args->limits.max_eh_states,
                  "C++ exception states per function")
      ->check(CLI::Range(1u, 100000u));
  sub->add_option("--max_eh_try_blocks", args->limits.max_eh_try_blocks,
                  "C++ try blocks per function")
      ->check(CLI::Range(1u, 100000u));
  sub->add_option("--max_eh_ip_map_entries", args->limits.max_eh_ip_map_entries,
                  "C++ IP map entries per function")
      ->check(CLI::Range(1u, 100000u));
  sub->add_option("--max_seh_scope_entries", args->limits.max_seh_scope_entries,
                  "SEH scope entries per function")
      ->check(CLI::Range(1u, 100000u));
  sub->add_option("--backward_scan_limit", args->limits.backward_scan_limit,
                  "Instructions scanned back for a jump table base")
      ->check(CLI::Range(1u, 10000u));
  sub->add_option("--max_jump_table_entries", args->limits.max_jump_table_entries,
                  "Jump table entries accepted")
      ->check(CLI::Range(1u, 100000u));
  sub->add_option("--max_blocks_per_function", args->limits.max_blocks_per_function,
                  "Basic blocks per function")
      ->check(CLI::Range(1u, 1000000u));

  sub->callback([args, &ctx, &pending]() {
    pending = [args, &ctx]() -> Result<void> {
      std::string path = args->config_path;
      if (path.empty()) {
        auto discovered = DiscoverManifestInCwd();
        if (!discovered)
          return Err<void>(discovered.error());
        path = *discovered;
      }
      return CodegenFromConfig(path, ctx, args->targets, args->ignore_stamp, args->limits);
    };
  });
}

