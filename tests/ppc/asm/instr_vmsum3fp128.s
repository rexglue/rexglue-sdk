test_vmsum3fp128_nan_inputs:
  # Every NaN result is 0x7FC00000. With two NaN inputs, x86 DPPS returns one of the input
  # payloads, and which one depends on the CPU vendor.
  #_ REGISTER_IN v3 [7FC11111, 3F800000, FFC22222, 01020304]
  #_ REGISTER_IN v4 [3F800000, 3F800000, 3F800000, 01020304]
  vmsum3fp128 v5, v3, v4
  blr
  #_ REGISTER_OUT v3 [7FC11111, 3F800000, FFC22222, 01020304]
  #_ REGISTER_OUT v4 [3F800000, 3F800000, 3F800000, 01020304]
  #_ REGISTER_OUT v5 [7FC00000, 7FC00000, 7FC00000, 7FC00000]

test_vmsum3fp128_nan_in_unused_lane:
