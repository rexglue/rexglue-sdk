test_vmsum3fp128_overflow:
  # A dot product of finite inputs that overflows gives QNaN in every lane, as on hardware.
  # v3 = [-FLT_MAX, -FLT_MAX, -FLT_MAX, 0.0]
  #_ REGISTER_IN v3 [FF7FFFFF, FF7FFFFF, FF7FFFFF, 00000000]
  vmsum3fp128 v5, v3, v3
  blr
  #_ REGISTER_OUT v3 [FF7FFFFF, FF7FFFFF, FF7FFFFF, 00000000]
  #_ REGISTER_OUT v5 [7FC00000, 7FC00000, 7FC00000, 7FC00000]

test_vmsum3fp128_negative_overflow:
  # Overflow towards -inf gives the same QNaN.
  #_ REGISTER_IN v3 [FF7FFFFF, FF7FFFFF, 3F800000, 00000000]
  #_ REGISTER_IN v4 [7F7FFFFF, 7F7FFFFF, 3F800000, 00000000]
  vmsum3fp128 v5, v3, v4
  blr
  #_ REGISTER_OUT v3 [FF7FFFFF, FF7FFFFF, 3F800000, 00000000]
  #_ REGISTER_OUT v4 [7F7FFFFF, 7F7FFFFF, 3F800000, 00000000]
  #_ REGISTER_OUT v5 [7FC00000, 7FC00000, 7FC00000, 7FC00000]

test_vmsum3fp128_overflow_cancels:
  # Products that overflow float32 but cancel: the float64 sum is 0, not inf - inf.
  # v3 = [FLT_MAX, -FLT_MAX, 1.0, 0.0], v4 = [2.0, 2.0, 0.0, 0.0]
  #_ REGISTER_IN v3 [7F7FFFFF, FF7FFFFF, 3F800000, 00000000]
  #_ REGISTER_IN v4 [40000000, 40000000, 00000000, 00000000]
  vmsum3fp128 v5, v3, v4
  blr
  #_ REGISTER_OUT v3 [7F7FFFFF, FF7FFFFF, 3F800000, 00000000]
  #_ REGISTER_OUT v4 [40000000, 40000000, 00000000, 00000000]
  #_ REGISTER_OUT v5 [00000000, 00000000, 00000000, 00000000]

