test_vmsum4fp128_overflow:
  # A dot product of finite inputs that overflows gives QNaN in every lane, as on hardware.
  #_ REGISTER_IN v3 [FF7FFFFF, FF7FFFFF, FF7FFFFF, FF7FFFFF]
  vmsum4fp128 v5, v3, v3
  blr
  #_ REGISTER_OUT v3 [FF7FFFFF, FF7FFFFF, FF7FFFFF, FF7FFFFF]
  #_ REGISTER_OUT v5 [7FC00000, 7FC00000, 7FC00000, 7FC00000]

test_vmsum4fp128_negative_overflow:
  # Overflow towards -inf gives the same QNaN; the fourth element counts here.
  #_ REGISTER_IN v3 [3F800000, 3F800000, FF7FFFFF, FF7FFFFF]
  #_ REGISTER_IN v4 [3F800000, 3F800000, 7F7FFFFF, 7F7FFFFF]
  vmsum4fp128 v5, v3, v4
  blr
  #_ REGISTER_OUT v3 [3F800000, 3F800000, FF7FFFFF, FF7FFFFF]
  #_ REGISTER_OUT v4 [3F800000, 3F800000, 7F7FFFFF, 7F7FFFFF]
  #_ REGISTER_OUT v5 [7FC00000, 7FC00000, 7FC00000, 7FC00000]

