enum class ReadbackResolveMode {
  kDisabled,
  kFast,
  kSome,
  kFull,
};

struct SwapState {
  // Lock must be held when changing data in this structure.
  std::mutex mutex;
  // Dimensions of the framebuffer textures. Should match window size.
  uint32_t width = 0;
  uint32_t height = 0;
  // Current front buffer, being drawn to the screen.
  uintptr_t front_buffer_texture = 0;
  // Current back buffer, being updated by the CP.
  uintptr_t back_buffer_texture = 0;
  // Backend data
  void* backend_data = nullptr;
  // Whether the back buffer is dirty and a swap is pending.
  bool pending = false;
};

enum class SwapMode {
  kNormal,
  kIgnored,
};

enum class GammaRampType {
  kUnknown = 0,
  kTable,
  kPWL,
};

class CommandProcessor {
 public:
  enum class SwapPostEffect {
    kNone,
    kFxaa,
    kFxaaExtreme,
  };

  CommandProcessor(GraphicsSystem* graphics_system, system::KernelState* kernel_state);
  virtual ~CommandProcessor();

  uint32_t counter() const { return counter_; }
  void increment_counter() { counter_++; }

  Shader* active_vertex_shader() const { return active_vertex_shader_; }
  Shader* active_pixel_shader() const { return active_pixel_shader_; }

  virtual bool Initialize();
  virtual void Shutdown();

  void CallInThread(std::function<void()> fn);

  virtual void ClearCaches();
  virtual void InvalidateGpuMemory();

  // Requests a change of the draw resolution scale (the multiplier of the
  // internal rendering resolution) while the title is running. Callable from
  // any thread and cheap: it only records the request (replacing an older one
  // that hasn't been applied yet). The command processor applies it between
  // two guest frames by recreating everything that depends on the scale -
  // render targets and the EDRAM buffer, the texture cache with the resolved
  // textures, translated shaders and pipelines - which causes a hitch, and the
  // contents of render targets and resolved textures are lost. If the new scale
  // can't be set up (not enough memory, for instance), 1x is used instead.
  // With force_rebuild, everything is recreated even if the scale stays the
  // same. Changing the draw_resolution_scale_x, draw_resolution_scale_y or
  // resolution_scale cvar requests the scale they configure.
  static void RequestDrawResolutionScale(uint32_t x, uint32_t y, bool force_rebuild = false);

  // "Desired" is for the external thread managing the post-processing effect.
  SwapPostEffect GetDesiredSwapPostEffect() const { return swap_post_effect_desired_; }
  void SetDesiredSwapPostEffect(SwapPostEffect swap_post_effect);
  // Implementations must not make assumptions that the front buffer will
  // necessarily be a resolve destination - it may be a texture generated by any
  // means like written to by the CPU or loaded from a file (the disclaimer
  // screen right in the beginning of 4D530AA4 is not a resolved render target,
  // for instance).
  virtual void IssueSwap(uint32_t frontbuffer_ptr, uint32_t frontbuffer_width,
                         uint32_t frontbuffer_height) = 0;

  // May be called not only from the command processor thread when the command
  // processor is paused, and the termination of this function may be explicitly
  // awaited.
  virtual void InitializeShaderStorage(const std::filesystem::path& cache_root, uint32_t title_id,
                                       bool blocking);

  void InitializeRingBuffer(uint32_t ptr, uint32_t size_log2);
  void EnableReadPointerWriteBack(uint32_t ptr, uint32_t block_size_log2);

  void UpdateWritePointer(uint32_t value);

  void ExecutePacket(uint32_t ptr, uint32_t count);

  bool is_paused() const { return paused_; }
  void Pause();
  void Resume();

  bool Save(::rex::stream::ByteStream* stream);
  bool Restore(::rex::stream::ByteStream* stream);

 protected:
  struct IndexBufferInfo {
    xenos::IndexFormat format = xenos::IndexFormat::kInt16;
    xenos::Endian endianness = xenos::Endian::kNone;
    uint32_t count = 0;
    uint32_t guest_base = 0;
    size_t length = 0;
  };

  void WorkerThreadMain();
  virtual bool SetupContext() = 0;
  virtual void ShutdownContext() = 0;

  virtual void WriteRegister(uint32_t index, uint32_t value);
  uint32_t ReadRegisterValue(uint32_t index) const;
  virtual void WriteRegistersFromMem(uint32_t start_index, uint32_t* base, uint32_t num_registers);
  virtual void WriteRegisterRangeFromRing(memory::RingBuffer* ring, uint32_t base,
                                          uint32_t num_registers);
  void WriteALURangeFromRing(memory::RingBuffer* ring, uint32_t base, uint32_t num_registers);
  void WriteFetchRangeFromRing(memory::RingBuffer* ring, uint32_t base, uint32_t num_registers);
  void WriteBoolRangeFromRing(memory::RingBuffer* ring, uint32_t base, uint32_t num_registers);
  void WriteLoopRangeFromRing(memory::RingBuffer* ring, uint32_t base, uint32_t num_registers);
  void WriteREGISTERSRangeFromRing(memory::RingBuffer* ring, uint32_t base, uint32_t num_registers);
  void WriteALURangeFromMem(uint32_t start_index, uint32_t* base, uint32_t num_registers);
  void WriteFetchRangeFromMem(uint32_t start_index, uint32_t* base, uint32_t num_registers);
  void WriteBoolRangeFromMem(uint32_t start_index, uint32_t* base, uint32_t num_registers);
  void WriteLoopRangeFromMem(uint32_t start_index, uint32_t* base, uint32_t num_registers);
  void WriteREGISTERSRangeFromMem(uint32_t start_index, uint32_t* base, uint32_t num_registers);

  // The gamma ramps the presenter applies: the guest's own, composed with the
  // display output transfer (display_output_transfer, command_processor.cpp).
  const reg::DC_LUT_30_COLOR* gamma_ramp_256_entry_table() const;
  const reg::DC_LUT_PWL_DATA* gamma_ramp_pwl_rgb() const;
  virtual void OnGammaRamp256EntryTableValueWritten() {}
  virtual void OnGammaRampPWLValueWritten() {}
  // The guest wrote a ramp value: the composed ramp is made again, then the
  // backend is told (the virtuals above).
  void GammaRamp256EntryTableValueWritten();
  void GammaRampPWLValueWritten();
  // At a swap: takes a changed display_output_transfer.
  void UpdateDisplayOutputTransfer();

  virtual void MakeCoherent();
  virtual void PrepareForWait();
  // Called over and over while waiting for the guest to write more commands
  // (results of work already sent to the host GPU can be delivered here).
  virtual void PollWhileWaiting() {}
  virtual void ReturnFromWait();

  uint32_t ExecutePrimaryBuffer(uint32_t start_index, uint32_t end_index);
  virtual void OnPrimaryBufferEnd() {}
  void ExecuteIndirectBuffer(uint32_t ptr, uint32_t length);
  bool ExecutePacket(memory::RingBuffer* reader);
  bool ExecutePacketType0(memory::RingBuffer* reader, uint32_t packet);
  bool ExecutePacketType1(memory::RingBuffer* reader, uint32_t packet);
  bool ExecutePacketType2(memory::RingBuffer* reader, uint32_t packet);
  bool ExecutePacketType3(memory::RingBuffer* reader, uint32_t packet);
  bool ExecutePacketType3_ME_INIT(memory::RingBuffer* reader, uint32_t packet, uint32_t count);
  bool ExecutePacketType3_NOP(memory::RingBuffer* reader, uint32_t packet, uint32_t count);
  bool ExecutePacketType3_INTERRUPT(memory::RingBuffer* reader, uint32_t packet, uint32_t count);
  bool ExecutePacketType3_XE_SWAP(memory::RingBuffer* reader, uint32_t packet, uint32_t count);
  bool ExecutePacketType3_INDIRECT_BUFFER(memory::RingBuffer* reader, uint32_t packet,
                                          uint32_t count);
  bool ExecutePacketType3_WAIT_REG_MEM(memory::RingBuffer* reader, uint32_t packet, uint32_t count);
  bool ExecutePacketType3_REG_RMW(memory::RingBuffer* reader, uint32_t packet, uint32_t count);
  bool ExecutePacketType3_REG_TO_MEM(memory::RingBuffer* reader, uint32_t packet, uint32_t count);
  bool ExecutePacketType3_MEM_WRITE(memory::RingBuffer* reader, uint32_t packet, uint32_t count);
  bool ExecutePacketType3_COND_WRITE(memory::RingBuffer* reader, uint32_t packet, uint32_t count);
  bool ExecutePacketType3_EVENT_WRITE(memory::RingBuffer* reader, uint32_t packet, uint32_t count);
  bool ExecutePacketType3_EVENT_WRITE_SHD(memory::RingBuffer* reader, uint32_t packet,
                                          uint32_t count);
  bool ExecutePacketType3_EVENT_WRITE_EXT(memory::RingBuffer* reader, uint32_t packet,
                                          uint32_t count);
  virtual bool ExecutePacketType3_EVENT_WRITE_ZPD(memory::RingBuffer* reader, uint32_t packet,
                                                  uint32_t count);
  bool ExecutePacketType3Draw(memory::RingBuffer* reader, uint32_t packet, const char* opcode_name,
                              uint32_t viz_query_condition, uint32_t count_remaining);
  bool ExecutePacketType3_DRAW_INDX(memory::RingBuffer* reader, uint32_t packet, uint32_t count);
  bool ExecutePacketType3_DRAW_INDX_2(memory::RingBuffer* reader, uint32_t packet, uint32_t count);
  bool ExecutePacketType3_SET_CONSTANT(memory::RingBuffer* reader, uint32_t packet, uint32_t count);
  bool ExecutePacketType3_SET_CONSTANT2(memory::RingBuffer* reader, uint32_t packet,
                                        uint32_t count);
  bool ExecutePacketType3_LOAD_ALU_CONSTANT(memory::RingBuffer* reader, uint32_t packet,
                                            uint32_t count);
  bool ExecutePacketType3_SET_SHADER_CONSTANTS(memory::RingBuffer* reader, uint32_t packet,
                                               uint32_t count);
  bool ExecutePacketType3_IM_LOAD(memory::RingBuffer* reader, uint32_t packet, uint32_t count);
  bool ExecutePacketType3_IM_LOAD_IMMEDIATE(memory::RingBuffer* reader,

                                            uint32_t packet, uint32_t count);
  bool ExecutePacketType3_INVALIDATE_STATE(memory::RingBuffer* reader, uint32_t packet,
                                           uint32_t count);
  bool ExecutePacketType3_VIZ_QUERY(memory::RingBuffer* reader, uint32_t packet, uint32_t count);

  virtual Shader* LoadShader(xenos::ShaderType shader_type, uint32_t guest_address,
                             const uint32_t* host_address, uint32_t dword_count) = 0;

  virtual bool IssueDraw(xenos::PrimitiveType prim_type, uint32_t index_count,
                         IndexBufferInfo* index_buffer_info, bool major_mode_explicit) = 0;
  virtual bool IssueCopy() = 0;

  // "Actual" is for the command processor thread, to be read by the
  // implementations.
  SwapPostEffect GetActualSwapPostEffect() const { return swap_post_effect_actual_; }

  // Shared readback resolve mode with backend legacy-flag alias support.
  ReadbackResolveMode GetReadbackResolveMode(bool legacy_readback_resolve_enabled) const;
  // Shared memexport readback enable state with backend legacy-flag override support.
  bool IsReadbackMemexportEnabled(bool legacy_backend_flag) const;

  // For the implementations, on the command processor thread at the end of a
  // frame: returns whether a RequestDrawResolutionScale request should be
  // applied now, and takes it. A request is returned only once it has stayed
  // the same for a whole frame - the scale cvars are usually changed one after
  // another, each change making a request, and the intermediate combinations
  // shouldn't cause a rebuild each.
  bool TakeDrawResolutionScaleRequest(uint32_t& x_out, uint32_t& y_out, bool& force_rebuild_out);

  memory::Memory* memory_ = nullptr;
  system::KernelState* kernel_state_ = nullptr;
  GraphicsSystem* graphics_system_ = nullptr;
  RegisterFile* register_file_ = nullptr;

  std::atomic<bool> worker_running_;
  system::object_ref<system::XHostThread> worker_thread_;

  std::queue<std::function<void()>> pending_fns_;

  // MicroEngine binary from PM4_ME_INIT
  std::vector<uint32_t> me_bin_;

  uint32_t counter_ = 0;

  // Resolves into a buffer the guest has presented with a swap: the guest's
  // CPU doesn't read those, so readback_resolve skips them (a full-screen
  // copy to host memory and into guest memory every frame otherwise).
  bool IsPresentedFrontbuffer(uint32_t physical_address) const;
  std::array<uint32_t, 4> presented_frontbuffers_ = {};
  uint32_t presented_frontbuffer_next_ = 0;

  // readback_resolve_cpu_reads_only: for the implementations, on the command
  // processor thread, after a resolve readback_resolve would copy back:
  // whether to copy it back now. Only destinations the guest has accessed
  // since they were first resolved to are. Any other one is read-watched
  // (rex/system/xmemory_read_watch.h): its first access waits while it is
  // copied back on the spot (ReadBackResolvesNow), and from then on it is
  // copied back after each resolve like before. format is the resolve's
  // xenos::ColorFormat, for the downscale at a draw resolution scale.
  bool ShouldReadbackResolve(uint32_t physical_address, uint32_t length, uint32_t format);

  // A resolve destination a guest thread is waiting for.
  struct ResolveFetch {
    uint32_t address;  // Physical.
    uint32_t length;
    uint32_t format;
    uint64_t serial;
    bool in_progress;  // Being copied back by the command processor thread.
    bool cancelled;    // The waiting thread gave up: don't write guest memory.
  };
  // For the implementations, on the command processor thread: copies resolve
  // destinations from the GPU's memory to host memory now, waiting for the
  // GPU. data_out gets a pointer to each one's bytes (nullptr where that
  // failed), valid until the next submission. Implementations that can't do
  // this return false from CanReadBackResolvesNow; every resolve is copied
  // back then.
  virtual bool CanReadBackResolvesNow() const { return false; }
  virtual void ReadBackResolvesNow(const ResolveFetch* /* fetches */, size_t count,
                                   std::vector<const uint8_t*>& data_out) {
    data_out.assign(count, nullptr);
  }
  // For the implementations, after a resolve ShouldReadbackResolve said to
  // copy back: copies the resolve's bytes (`data`, `length` of them) into
  // guest memory at `physical_address`, all of them or, for a destination in
  // pieces (readback_resolve_cpu_pages_only), the pieces the guest reads.
  // Returns how many bytes were copied.
  uint64_t CopyResolveToGuest(uint32_t physical_address, uint32_t length, const uint8_t* data);
  // The same in two steps, for an implementation that also copies only the
  // pieces from the GPU: which pieces (offset, length) a resolve's copy back
  // is, or true for all of it; then the copy of those.
  bool GetResolveCopyPieces(uint32_t physical_address, uint32_t length,
                            std::vector<std::pair<uint32_t, uint32_t>>& pieces);
  uint64_t CopyResolvePiecesToGuest(uint32_t physical_address, uint32_t length,
                                    const uint8_t* data, bool all,
                                    const std::vector<std::pair<uint32_t, uint32_t>>& pieces);

  // Copies back the resolves guest threads are waiting for. On the command
  // processor thread between packets and while it waits; cheap when none.
  void ProcessResolveFetches() {
    if (resolve_fetch_requested_.load(std::memory_order_acquire)) {
      ProcessResolveFetchesNow();
    }
  }

  uint32_t primary_buffer_ptr_ = 0;
  uint32_t primary_buffer_size_ = 0;

  uint32_t read_ptr_index_ = 0;
  uint32_t read_ptr_update_freq_ = 0;
  uint32_t read_ptr_writeback_ptr_ = 0;

  std::unique_ptr<rex::thread::Event> write_ptr_index_event_;
  std::atomic<uint32_t> write_ptr_index_;

  // Some titles submit writes beyond the emulated register file range in PM4
  // packets. Preserve these values so dependent packet logic can still observe
  // them instead of dropping the write entirely.
  std::unordered_map<uint32_t, uint32_t> extended_register_values_;

  uint64_t bin_select_ = 0xFFFFFFFFull;
  uint64_t bin_mask_ = 0xFFFFFFFFull;

  Shader* active_vertex_shader_ = nullptr;
  Shader* active_pixel_shader_ = nullptr;

  bool paused_ = false;

  // By default (such as for tools), post-processing is disabled.
  // "Desired" is for the external thread managing the post-processing effect.
  SwapPostEffect swap_post_effect_desired_ = SwapPostEffect::kNone;
  SwapPostEffect swap_post_effect_actual_ = SwapPostEffect::kNone;

  // Set by backend command processors to their legacy memexport readback cvar
  // name (for explicit-override compatibility).
  const char* legacy_readback_memexport_cvar_name_ = nullptr;

 private:
  // The pending draw resolution scale request seen at the previous end of a
  // frame (in the packed form, 0 if none).
  uint32_t draw_resolution_scale_request_seen_ = 0;

  // readback_resolve_cpu_reads_only (see ShouldReadbackResolve).
  struct ResolveDestination {
    uint32_t address;  // Physical.
    uint32_t length;
    uint32_t format;
    // Its copy for the guest's first access, 0 if none.
    uint64_t fetch_serial;
    // The guest has accessed it: copied back after each resolve.
    bool cpu_reads;
    bool cpu_reads_logged;
    // readback_resolve_cpu_pages_only: the 4 KB pieces of it the guest has
    // touched, a bit each from the one holding `address`. After each resolve
    // only these are copied back; the others stay watched, and touching one
    // brings in this resolve's data (one fetch per resolve) and adds it here.
    std::vector<uint64_t> read_chunks;
    uint32_t read_chunk_count;
    // The guest's copy of all of it holds the last resolve's data (a whole
    // copy or a fetch since that resolve): touching a watched piece then only
    // needs it unwatched.
    bool current;
    // Copied back whole after each resolve: pages-only is off, or the guest
    // has touched too much of it for pieces to pay.
    bool whole;
  };
  // The 4 KB pieces readback_resolve_cpu_pages_only works in.
  static constexpr uint32_t kResolveChunkShift = 12;
  // Marks the pieces of a destination that a touched physical range covers
  // as read; returns whether any was new.
  static bool MarkResolveChunksRead(ResolveDestination& destination, uint32_t physical_address,
                                    uint32_t length);
  // Watches the pieces of a destination the guest hasn't touched (for the
  // data of the resolve just made).
  void WatchUnreadResolveChunks(const ResolveDestination& destination);
  // Called by the memory system on the thread that touched a read-watched
  // page, with the global critical region locked once.
  static std::pair<uint32_t, uint32_t> ResolveReadCallbackThunk(
      void* context, std::unique_lock<std::recursive_mutex>& global_lock,
      uint32_t physical_address_start, uint32_t length);
  std::pair<uint32_t, uint32_t> ResolveReadCallback(
      std::unique_lock<std::recursive_mutex>& global_lock, uint32_t physical_address_start,
      uint32_t length);
  void ProcessResolveFetchesNow();
  // Writes a fetched destination into guest memory, the pages still
  // read-watched only (the others were written or freed since its resolve).
  void CopyResolveFetchToGuest(const ResolveFetch& fetch, const uint8_t* data);
  // A destination is remembered while the guest may still access it; past
  // this many, new ones are copied back after every resolve like before.
  static constexpr size_t kMaxResolveDestinations = 256;
  // Guarded by the global critical region.
  std::vector<ResolveDestination> resolve_destinations_;
  // CopyResolveToGuest's pieces (offset, length), kept for their storage.
  std::vector<std::pair<uint32_t, uint32_t>> resolve_copy_runs_;
  void* resolve_read_callback_handle_ = nullptr;
  // Host thread ID of the command processor thread, which can't wait for
  // itself.
  std::atomic<uint32_t> worker_thread_id_{0};
  std::mutex resolve_fetch_mutex_;
  std::condition_variable resolve_fetch_cv_;
  // Queued and in progress; guarded by resolve_fetch_mutex_ (taken after the
  // global critical region, never before).
  std::vector<ResolveFetch> resolve_fetches_;
  uint64_t resolve_fetch_next_serial_ = 1;
  std::atomic<bool> resolve_fetch_requested_{false};
  std::atomic<uint32_t> resolve_read_callbacks_running_{0};
  // Command processor thread only.
  std::vector<ResolveFetch> resolve_fetch_batch_;
  std::vector<const uint8_t*> resolve_fetch_data_;

  reg::DC_LUT_30_COLOR gamma_ramp_256_entry_table_[256] = {};
  reg::DC_LUT_PWL_DATA gamma_ramp_pwl_rgb_[128][3] = {};
  uint32_t gamma_ramp_rw_component_ = 0;
  // The ramps as presented (the guest's composed with the display output
  // transfer), made again from the guest's when one of them is out of date.
  // Command processor thread only.
  mutable reg::DC_LUT_30_COLOR display_gamma_ramp_256_entry_table_[256] = {};
  mutable reg::DC_LUT_PWL_DATA display_gamma_ramp_pwl_rgb_[128][3] = {};
  mutable bool display_gamma_ramp_256_entry_table_stale_ = true;
  mutable bool display_gamma_ramp_pwl_stale_ = true;
  bool display_output_bt1886_ = false;
};

